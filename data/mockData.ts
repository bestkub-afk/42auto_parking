const createSpots = () => {
  const spots: Spot[] = [];
  for (const floor of FLOORS) {
    for (const row of ROWS) {
      for (let number = 1; number <= SPOTS_PER_ROW; number++) {
        spots.push({ id: `f${floor}-${row}${number}`, name: `${row}${number}`, floor, blocked: false });
      }
    }
  }
  return spots;
};

